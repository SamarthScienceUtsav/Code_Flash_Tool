import { mkdir, rm, writeFile } from "node:fs/promises";
import { join } from "node:path";

const folderId = "12w02nJfTBFPVHQIK7ImZ8iMsDpza86Y-";
const response = await fetch(`https://drive.google.com/embeddedfolderview?id=${folderId}#list`);
if (!response.ok) throw new Error(`Google Drive folder listing failed (${response.status}).`);

const html = await response.text();
const files = [...html.matchAll(/class="flip-entry" id="entry-([^"]+)"[\s\S]*?class="flip-entry-title">([\s\S]*?)<\/div>/g)]
  .map(match => ({ id: match[1], name: match[2].replace(/<[^>]*>/g, "").trim(), size: 0 }))
  .filter(file => /\.(?:bin|hex)$/i.test(file.name));

if (!files.length) throw new Error("No .bin or .hex firmware files were found in the public Drive folder.");

const firmwareDirectory = join(process.cwd(), "public", "firmware");
await rm(firmwareDirectory, { recursive: true, force: true });
await mkdir(firmwareDirectory, { recursive: true });

for (const file of files) {
  const extension = file.name.toLowerCase().endsWith(".hex") ? ".hex" : ".bin";
  file.path = `firmware/${file.id}${extension}`;
  const download = await fetch(`https://drive.google.com/uc?export=download&id=${encodeURIComponent(file.id)}`);
  if (!download.ok) throw new Error(`Download failed for ${file.name} (${download.status}).`);
  const bytes = new Uint8Array(await download.arrayBuffer());
  const prefix = new TextDecoder().decode(bytes.slice(0, 32)).toLowerCase();
  if (prefix.includes("<!doctype") || prefix.includes("<html")) throw new Error(`Google Drive returned a web page instead of ${file.name}.`);
  await writeFile(join(process.cwd(), "public", file.path), bytes);
}

const source = `// Generated by scripts/sync-drive-files.mjs during the Pages build.\nexport const driveFiles = ${JSON.stringify(files, null, 2)} as const;\n`;
await writeFile(join(process.cwd(), "app", "drive-files.generated.ts"), source, "utf8");
console.log(`Synced ${files.length} firmware files from Google Drive.`);
