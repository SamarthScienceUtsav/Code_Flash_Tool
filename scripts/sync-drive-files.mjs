import { writeFile } from "node:fs/promises";
import { join } from "node:path";

const folderId = "12w02nJfTBFPVHQIK7ImZ8iMsDpza86Y-";
const response = await fetch(`https://drive.google.com/embeddedfolderview?id=${folderId}#list`);
if (!response.ok) throw new Error(`Google Drive folder listing failed (${response.status}).`);

const html = await response.text();
const files = [...html.matchAll(/class="flip-entry" id="entry-([^"]+)"[\s\S]*?class="flip-entry-title">([\s\S]*?)<\/div>/g)]
  .map(match => ({ id: match[1], name: match[2].replace(/<[^>]*>/g, "").trim(), size: 0 }))
  .filter(file => /\.(?:bin|hex)$/i.test(file.name));

if (!files.length) throw new Error("No .bin or .hex firmware files were found in the public Drive folder.");

const source = `// Generated by scripts/sync-drive-files.mjs during the Pages build.\nexport const driveFiles = ${JSON.stringify(files, null, 2)} as const;\n`;
await writeFile(join(process.cwd(), "app", "drive-files.generated.ts"), source, "utf8");
console.log(`Synced ${files.length} firmware files from Google Drive.`);
